#!/usr/bin/env python3
"""Give client-side-decorated windows the same buttons as the MoOS frame.

KWin draws every server-side MoOS frame from an Aurorae theme. GTK3, GTK4,
libadwaita and Chromium/Electron's GTK caption buttons draw their own. Plasma's
gtkconfig bridge is meant to copy the KWin buttons into GTK, but it cannot
paint QML Aurorae decorations: on the live V3 every image it wrote was an empty
50x50 SVG, and nothing imported them. So a MoOS window had coloured MoOS
buttons while the app next to it had grey Adwaita circles or plain glyphs.

This generator cuts each Aurorae button state (`<state>-center`) out of the
shipped MoOS themes into standalone SVGs and writes one GTK stylesheet per
theme. moos-theme copies the set that matches the live KWin frame into
~/.config/gtk-{3,4}.0 (which Flatpak apps can read) and imports it. The
Aurorae files stay the single source of the artwork.

    python3 artwork/generate_moos_window_controls.py          # write
    python3 artwork/generate_moos_window_controls.py --check  # compare only
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
THEMES = ROOT / "system_files/usr/share/aurorae/themes"
OUT = ROOT / "system_files/usr/share/moos/window-controls"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)

BUTTONS = ("close", "minimize", "maximize", "restore")
STATES = ("active", "inactive", "hover", "hover-inactive", "pressed",
          "pressed-inactive", "deactivated", "deactivated-inactive")
# The visible MoOS tile is 24px inside its native 44px target. Old 20px inputs
# are also understood when reviewing a predecessor. Both source geometries are
# cut to the same 24-unit square so every family has the same GTK footprint.
CROPS = {"0 0 44 44": "10 10 24 24", "0 0 20 20": "-2 -2 24 24"}
SIZE = 24
# GTK pseudo-classes for each Aurorae state. :backdrop is GTK's unfocused window.
PSEUDO = (
    ("", "active"),
    (":hover", "hover"),
    (":active", "pressed"),
    (":backdrop", "inactive"),
    (":backdrop:hover", "hover-inactive"),
    (":backdrop:active", "pressed-inactive"),
    (":disabled", "deactivated"),
    (":backdrop:disabled", "deactivated-inactive"),
)
THEME_NAME = re.compile(r"^MoOSUI2[A-Za-z0-9]*$")


def themes() -> list[pathlib.Path]:
    found = sorted(path for path in THEMES.iterdir()
                   if path.is_dir() and THEME_NAME.fullmatch(path.name))
    if not found:
        raise SystemExit("no MoOS Aurorae themes found")
    return found


def state_svg(source: pathlib.Path, state: str) -> str:
    root = ET.parse(source).getroot()
    view = " ".join(root.get("viewBox", "").split())
    if view not in CROPS:
        raise SystemExit(f"{source}: unsupported button geometry {view!r}")
    groups = [element for element in root.iter(f"{{{SVG}}}g")
              if element.get("id") == f"{state}-center"]
    if len(groups) != 1:
        raise SystemExit(f"{source}: expected one {state}-center group, found {len(groups)}")
    group = groups[0]
    for element in group.iter():
        for attribute in element.attrib:
            if "href" in attribute:
                raise SystemExit(f"{source}: {state} references another element")
    defs = [ET.tostring(element, encoding="unicode") for element in root
            if element.tag == f"{{{SVG}}}defs"]
    body = (ET.tostring(group, encoding="unicode")
            .replace(f' xmlns="{SVG}"', "", 1).replace(f' id="{state}-center"', "", 1))
    return ("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
            f'<svg xmlns="{SVG}" width="{SIZE}" height="{SIZE}" viewBox="{CROPS[view]}">'
            f"{''.join(defs)}{body}</svg>\n")


def stylesheet(theme: str) -> str:
    directory = f"moos-window-controls/{theme}"
    gtk3 = "headerbar button.titlebutton.{0}, .titlebar button.titlebutton.{0}"
    gtk4 = "windowcontrols > button.{0}"
    every = ",\n".join(selector.format(button) for button in ("close", "minimize", "maximize")
                       for selector in (gtk3, gtk4))
    lines = [
        f"/* MoOS window controls: the {theme} frame's own buttons for client-side",
        " * decorations (GTK3, GTK4, libadwaita, Chromium/Electron GTK captions).",
        " * Generated by artwork/generate_moos_window_controls.py; installed and",
        " * removed by moos-theme with the live KWin frame. Do not edit. */",
        f"{every} {{",
        "  min-width: 44px;",
        "  min-height: 44px;",
        "  padding: 0;",
        "  margin: 0 1px;",
        "  border: none;",
        "  border-radius: 0;",
        "  box-shadow: none;",
        "  background-color: transparent;",
        "  background-repeat: no-repeat;",
        "  background-position: center;",
        f"  background-size: {SIZE}px {SIZE}px;",
        "}",
        # The native icon (and libadwaita's grey disc, painted on the image)
        # keeps its size but is not drawn: the MoOS state image replaces it.
        ",\n".join(selector.format(button) + " > image"
                   for button in ("close", "minimize", "maximize")
                   for selector in ("headerbar button.titlebutton.{0}",
                                    ".titlebar button.titlebutton.{0}", gtk4)) + " {",
        "  opacity: 0;",
        "}",
    ]
    for button in ("close", "minimize", "maximize"):
        for pseudo, state in PSEUDO:
            selectors = [gtk3.format(button).replace(f".{button}", f".{button}{pseudo}"),
                         gtk4.format(button) + pseudo]
            lines.append(f"{', '.join(selectors)} {{")
            lines.append(f'  background-image: url("{directory}/{button}-{state}.svg");')
            lines.append("}")
    # A maximized window offers restore in the maximize slot, as KWin does.
    for pseudo, state in PSEUDO:
        selectors = [f".maximized headerbar button.titlebutton.maximize{pseudo}",
                     f".maximized .titlebar button.titlebutton.maximize{pseudo}",
                     f"window.maximized windowcontrols > button.maximize{pseudo}"]
        lines.append(f"{', '.join(selectors)} {{")
        lines.append(f'  background-image: url("{directory}/restore-{state}.svg");')
        lines.append("}")
    return "\n".join(lines) + "\n"


def expected() -> dict[pathlib.Path, str]:
    files: dict[pathlib.Path, str] = {}
    for theme in themes():
        target = OUT / theme.name
        for button in BUTTONS:
            source = theme / f"{button}.svg"
            if not source.is_file():
                raise SystemExit(f"{source} is missing")
            for state in STATES:
                files[target / f"{button}-{state}.svg"] = state_svg(source, state)
        files[target / "window-controls.css"] = stylesheet(theme.name)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    files = expected()
    present = {path for path in OUT.rglob("*") if path.is_file()} if OUT.exists() else set()
    if arguments.check:
        stale = sorted(str(path.relative_to(ROOT)) for path in present - set(files))
        wrong = sorted(str(path.relative_to(ROOT)) for path, text in files.items()
                       if not path.is_file() or path.read_text(encoding="utf-8") != text)
        if stale or wrong:
            print("window controls differ from their Aurorae source; run "
                  "python3 artwork/generate_moos_window_controls.py", file=sys.stderr)
            for name in (wrong + stale)[:20]:
                print(f"  {name}", file=sys.stderr)
            return 1
        print(f"window controls match {len(files)} generated files")
        return 0
    for path in present - set(files):
        path.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} window-control files for {len(themes())} MoOS frames")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
