#!/usr/bin/env python3
"""Connect the shared session design to Plasma 6.8's native control owner.

The upstream shell owns the countdown, output handoff and power signals. The
older look-and-feel host uses the canonical Logout.qml directly. This adapter
derives the same visual engine without creating a second timer or executor.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / 'system_files/usr/lib64/qt6/qml/org/moos/ui'
CANONICAL = ROOT / 'system_files/usr/share/plasma/look-and-feel/org.moos.ui2/contents/logout'


def once(body, old, new):
    if body.count(old) != 1:
        raise ValueError('Session adapter source changed: ' + old[:90])
    return body.replace(old, new, 1)


def outputs():
    profiles = json.loads((ROOT / 'artwork/moos-design/theme-profiles.json').read_text())['profiles']
    wallpapers = {}
    for profile in profiles:
        filename = '1672x941.png' if profile['family'] == 'bloom' else '3840x2160.jpg'
        wallpapers[profile['id']] = 'wallpapers/' + profile['wallpaper'] + '/contents/' + profile['wallpaperBranch'] + '/' + filename
    packages = {profile['wallpaper']: wallpapers[profile['id']].split('/contents/',1)[1]
                for profile in profiles}
    resolver = '''.pragma library
// Generated from the canonical theme profiles. Desktop and login use one map.
var packageImages = %s;
function imageForPackage(path) {
    var base = String(path || "").replace(/\\/+$/, "");
    var name = base.substring(base.lastIndexOf("/") + 1);
    return packageImages[name] ? base + "/contents/" + packageImages[name] : "";
}
''' % json.dumps(packages,ensure_ascii=False,indent=4)
    appearance = '''// Generated by artwork/generate_moos_session.py. No settings are written.
pragma Singleton
import QtQuick
import QtCore

QtObject {
    id: appearance
    readonly property var wallpapers: %s
    property Component reader: Component { Settings {} }

    function configuredLook() {
        const files = StandardPaths.locateAll(StandardPaths.GenericConfigLocation, "kdeglobals");
        for (const path of files) {
            const config = reader.createObject(appearance, {location: path, category: "KDE"});
            const value = String(config.value("LookAndFeelPackage", ""));
            config.destroy();
            if (value !== "") return value;
        }
        return "org.moos.ui2";
    }
    function wallpaperForLook(look) {
        const relative = wallpapers[look] || wallpapers["org.moos.ui2"];
        return StandardPaths.locate(StandardPaths.GenericDataLocation, relative);
    }
    function configuredWallpaper() {
        return wallpaperForLook(configuredLook());
    }
}
''' % json.dumps(wallpapers, ensure_ascii=False, indent=8)
    body = (CANONICAL / 'Logout.qml').read_text()
    body = once(body, '    width: screenGeometry.width\n    height: screenGeometry.height', '''    anchors.fill: parent
    required property Item sessionHost
    required property var cancelCountdown
    readonly property Item hostRoot: sessionHost
    readonly property string activeLook: MoUI.SessionAppearance.configuredLook()
    readonly property url sceneWallpaper: MoUI.SessionAppearance.wallpaperForLook(activeLook)
    objectName: "moosSessionPower"
    onHostRootChanged: {
        disarm();
        Qt.callLater(root.focusInitialAction);
    }''')
    body = once(body, '    property int remainingTime: 30', '    readonly property real remainingTime: sessionHost.remainingTime')
    start = body.index('    function stopCountdown()')
    end = body.index('    function visibleDockActions()', start)
    body = body[:start] + '    function stopCountdown() { root.cancelCountdown(); }\n\n' + body[end:]
    start = body.index('    Timer {\n        id: countdownTimer')
    end = body.index('    Component.onCompleted:', start)
    body = body[:start] + body[end:]
    body = once(body, 'visible: countdownTimer.running', 'visible: root.sessionHost.countingDown')
    body = once(body, 'source: Qt.resolvedUrl("../previews/fullscreenpreview.jpg")', 'source: root.sceneWallpaper')
    body = body.replace('MoOSUI2ActionButton {', 'SessionPowerButton {')
    # Keep every destination on the native root connected to its native C++
    # owner. No subprocess, D-Bus command or independent power implementation.
    signals = ('logoutRequested', 'haltRequested', 'haltUpdateRequested',
               'rebootRequested', 'rebootUpdateRequested', 'cancelRequested',
               'lockScreenRequested', 'cancelSoftwareUpdateRequested')
    handlers = '\n'.join('    on'+name[0].upper()+name[1:]+': root.sessionHost.'+name+'()' for name in signals)
    handlers += '\n    onSuspendRequested: method => root.sessionHost.suspendRequested(method)'
    handlers += '\n    onRebootRequested2: option => root.sessionHost.rebootRequested2(option)\n'
    body = once(body, '    signal cancelSoftwareUpdateRequested()', '    signal cancelSoftwareUpdateRequested()\n\n'+handlers)
    # The 6.8 host exposes pending firmware/boot-entry intent. Preserve its
    # warnings as well as capabilities/update routes, rather than hiding them
    # behind the legacy visual implementation.
    warning = '''            QQC2.Label {
                objectName: "moosPowerBootIntent"
                Layout.alignment: Qt.AlignHCenter
                Layout.maximumWidth: sheet.width - root.design.space6
                horizontalAlignment: Text.AlignHCenter
                wrapMode: Text.Wrap
                textFormat: Text.PlainText
                visible: rebootToFirmwareSetup || rebootToBootLoaderMenu || rebootToBootLoaderEntry !== ""
                text: rebootToFirmwareSetup
                    ? root.bilingual("ستفتح إعدادات الجهاز بعد إعادة التشغيل", "Restart will open firmware settings")
                    : rebootToBootLoaderMenu
                    ? root.bilingual("ستفتح قائمة الإقلاع بعد إعادة التشغيل", "Restart will open the boot menu")
                    : root.bilingual("سيبدأ الإقلاع من: ", "Restart will use: ") + rebootToBootLoaderEntry
                color: Kirigami.Theme.neutralTextColor
            }

'''
    body = once(body, '            // ── The power dock:', warning+'            // ── The power dock:')
    body = once(body, '    Component.onCompleted: Qt.callLater(root.focusInitialAction)', '''    Component.onCompleted: {
        Qt.callLater(root.focusInitialAction);
        console.info("MOOS_SESSION_POWER_READY", Qt.resolvedUrl("SessionPower.qml"), activeLook, sceneWallpaper);
    }''')
    body = '// Generated native control view; canonical design: org.moos.ui2/contents/logout/Logout.qml.\n' + body
    result = {UI / 'SessionAppearance.qml': appearance,
              UI / 'SessionPower.qml': body,
              UI / 'SessionPowerButton.qml': (CANONICAL / 'MoOSUI2ActionButton.qml').read_text(),
              UI / 'WallpaperSources.js': resolver}
    # Legacy hosts and all look-and-feel packages retain the same visual source.
    # Do not re-render wallpapers or recolour a QML sibling to propagate this.
    for profile in profiles:
        logout = ROOT / 'system_files/usr/share/plasma/look-and-feel' / profile['id'] / 'contents/logout'
        for name in ('Logout.qml', 'MoOSUI2ActionButton.qml'):
            result[logout / name] = (CANONICAL / name).read_text()
    return result


def main():
    import argparse
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, body in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != body: stale.append(str(path.relative_to(ROOT)))
        elif not path.is_file() or path.read_text() != body:
            path.write_text(body)
    if stale: raise SystemExit('Stale session engine: ' + ', '.join(stale))
    print('MoOS native session engine is current')


if __name__ == '__main__': main()
