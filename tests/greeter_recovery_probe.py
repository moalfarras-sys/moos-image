#!/usr/bin/env python3
"""Opt-in native systemd dependency proof; never addresses a real greeter.

Run as an ordinary user with a running user manager. Only random, exclusively
created units below that user's runtime directory are loaded. The fixture has
the login target's Requires/BindsTo/PartOf edges but no display, input, password
or portal. Logs and results belong in a private review directory, not Git.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import uuid

ROOT = Path(__file__).resolve().parents[1]
DROP = ROOT / "system_files/usr/lib/systemd/user/plasma-login.service.d/20-moos-crash-recovery.conf"


def ctl(*args, check=True):
    return subprocess.run(["systemctl", "--user", *args], check=check,
                          capture_output=True, text=True, timeout=15)


def wait_until(predicate, seconds=10):
    end = time.monotonic() + seconds
    while time.monotonic() < end:
        if predicate():
            return
        time.sleep(.1)
    raise AssertionError("native fixture did not reach the required state")


def state(unit):
    result = ctl("show", unit, "-p", "ActiveState", "-p", "MainPID", "-p", "NRestarts")
    return dict(line.split("=", 1) for line in result.stdout.splitlines() if "=" in line)


def sample(dropin, mode, output):
    runtime = Path(os.environ["XDG_RUNTIME_DIR"])
    if runtime.stat().st_uid != os.getuid() or os.getuid() == 0:
        raise RuntimeError("use an ordinary user's own runtime and user manager")
    units_dir = runtime / "systemd/user"
    units_dir.mkdir(parents=True, exist_ok=True)
    prefix = "moos-private-greeter-" + uuid.uuid4().hex
    names = {key: prefix + suffix for key, suffix in (
        ("target", ".target"), ("main", "-main.service"),
        ("remote", "-remote.service"), ("kwin", "-compositor.service"))}
    made = []
    with tempfile.TemporaryDirectory(prefix=prefix + "-", dir=output) as temp:
        private = Path(temp)
        # Paths generated by mkdtemp contain no whitespace or unit specifiers.
        helper = private / "child.py"
        helper.write_text('''import pathlib, sys, time
p=pathlib.Path(sys.argv[1]); mode=sys.argv[2]
counter=p/'starts'; n=int(counter.read_text())+1 if counter.exists() else 1
counter.write_text(str(n))
while True:
    if (p/'exit').exists():
        if mode=='always' or n==1:
            sys.exit(0 if mode=='success' else 42)
    time.sleep(.05)
''')
        contents = {
            "target": ("[Unit]\nRequires={main} {kwin}\nBindsTo={main} {kwin}\nWants={remote}\n").format(**names),
            "main": ("[Unit]\nPartOf={target}\nAfter={kwin}\n[Service]\n"
                     "ExecStart=/usr/bin/python3 " + str(helper) + " " + str(private) + " " + mode + "\n").format(**names),
            "kwin": "[Service]\nExecStart=/usr/bin/sleep infinity\n",
            "remote": "[Unit]\nPartOf={target}\nBindsTo={kwin}\nAfter={kwin}\n[Service]\nExecStart=/usr/bin/sleep infinity\n".format(**names),
        }
        try:
            for key, content in contents.items():
                path = units_dir / names[key]
                with path.open("x") as stream:
                    stream.write(content)
                made.append(path)
            if dropin:
                directory = units_dir / (names["main"] + ".d")
                directory.mkdir()
                made.append(directory)
                path = directory / "20-recovery.conf"
                with path.open("x") as stream:
                    stream.write(dropin)
                made.append(path)
            ctl("daemon-reload")
            ctl("start", names["target"])
            wait_until(lambda: all(state(names[k])["ActiveState"] == "active" for k in names))
            before = {key: state(name) for key, name in names.items()}
            (private / "exit").touch()
            expected = "recovered" if "RestartMode=direct" in dropin and mode == "once" else "stopped"
            if expected == "recovered":
                wait_until(lambda: (private / "starts").read_text() == "2"
                           and state(names["main"])["ActiveState"] == "active")
                after = {key: state(name) for key, name in names.items()}
                assert after["target"]["ActiveState"] == "active", after
                assert after["remote"]["MainPID"] == before["remote"]["MainPID"], after
                assert after["kwin"]["MainPID"] == before["kwin"]["MainPID"], after
                ctl("stop", names["target"])
                time.sleep(2.5)
                assert (private / "starts").read_text() == "2", "explicit stop restarted the fixture"
                assert state(names["main"])["ActiveState"] == "inactive"
            else:
                wait_until(lambda: state(names["target"])["ActiveState"] == "inactive")
                after = {key: state(name) for key, name in names.items()}
                if dropin and mode == "always":
                    assert (private / "starts").read_text() == "3", after
                    assert after["main"]["ActiveState"] == "failed", after
                elif mode == "success":
                    time.sleep(2.5)
                    assert (private / "starts").read_text() == "1", "normal exit restarted the fixture"
            return {"mode": mode, "dropin": bool(dropin), "expected": expected,
                    "starts": int((private / "starts").read_text()), "before": before, "after": after}
        finally:
            ctl("stop", *names.values(), check=False)
            ctl("reset-failed", *names.values(), check=False)
            for path in reversed(made):
                path.rmdir() if path.is_dir() else path.unlink()
            ctl("daemon-reload")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True, mode=0o700)
    dropin = DROP.read_text()
    results = [sample("", "once", args.output),
               sample(dropin.replace("RestartMode=direct", "RestartMode=normal"), "once", args.output),
               sample(dropin, "once", args.output),
               sample(dropin, "always", args.output), sample(dropin, "success", args.output)]
    receipt = {"schema": 1, "scope": "private native systemd dependency fixtures; no real login/input/display",
               "systemd": ctl("--version").stdout.splitlines()[0], "results": results}
    (args.output / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
