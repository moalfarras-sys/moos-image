def latin(c):
    table=UPPER if c in UPPER else LOWER
    if c not in table:return None
    w,paths=table[c];g=Glyph(w,top=(round(w/2),815 if c.isupper() or c in 'bdhkl' else 620),bottom=(round(w/2),-300))
    for p in paths:g.add(P(*p))
    if c in 'OQ':g.add(E(370,355,285,365),1,True)
    if c=='o':g.add(E(292.5,255,215,263),1,True)
    if c in 'ij':g.dot(128 if c=='i' else 165,680,.88)
    return g


